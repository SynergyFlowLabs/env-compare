import { useMemo, useReducer, useRef, useState } from 'react';
import { Download, Eye, EyeOff, FileUp, ShieldCheck, Trash2, Wand2 } from 'lucide-react';
import { maskCsv, maskedText, type MaskMode } from '../../core/mask';
import { initialMaskState, maskReducer } from '../../state/maskReducer';
import { SAMPLE_CSV } from '../../state/sample';
import { SiteHeader } from '../components/SiteHeader';
import { SkipLink } from '../components/SkipLink';
import { Button } from '../components/ui/button';
import { copyText, downloadText, safeFileName } from '../lib/clipboard';
import { cn } from '../lib/utils';

/**
 * CSV masking (issue #10).
 *
 * The page exists because the two things people do with env data pull in
 * opposite directions: they want a model to reason about their configuration,
 * and they do not want the secrets in it to leave the tab. Masking is the
 * smallest honest answer — the keys and the structure go, the values do not.
 *
 * Three rules shaped the interface:
 *   1. The preview *is* the output. There is no separate "masked" file to trust;
 *      the table is generated by the same function that writes the CSV.
 *   2. Nothing is destructive. The original stays in memory, every mask can be
 *      undone, and the export is always derived from it.
 *   3. Masking is described as formatting, not encryption, because claiming
 *      more than that would be a lie a reader might rely on.
 */

const MODE_OPTIONS: Array<{ value: MaskMode; label: string; hint: string }> = [
  { value: 'none', label: 'Don’t mask', hint: 'Value is shared exactly as written' },
  { value: 'hide', label: 'Hide completely', hint: 'Replaced by 8 stars; even the length is hidden' },
  { value: 'start', label: 'Mask the start', hint: 'The last characters stay visible' },
  { value: 'middle', label: 'Mask the middle', hint: 'The first and last characters stay visible' },
  { value: 'end', label: 'Mask the end', hint: 'The first characters stay visible' },
];

const KEEP_OPTIONS = [2, 4, 6, 8];

const PREVIEW_LIMIT = 100;

export function Mask() {
  const [state, dispatch] = useReducer(maskReducer, initialMaskState);
  const [draft, setDraft] = useState('');
  const fileInput = useRef<HTMLInputElement>(null);

  const masked = useMemo(
    () =>
      state.table
        ? maskCsv(state.table, {
            columnModes: state.columnModes,
            keyModes: state.keyModes,
            keyColumn: state.keyColumn,
            keep: state.keep,
          })
        : null,
    [state.table, state.columnModes, state.keyModes, state.keyColumn, state.keep],
  );

  const output = useMemo(
    () =>
      masked && state.table
        ? maskedText(masked, {
            delimiter: state.table.delimiter,
            lineEnding: state.table.lineEnding,
          })
        : '',
    [masked, state.table],
  );

  const columnName = (index: number) =>
    state.table?.header[index]?.trim() || `Column ${index + 1}`;

  const load = (text: string, fileName = '') => {
    dispatch({ type: 'load', text, fileName });
    setDraft(text);
  };

  const openFile = async (file: File) => {
    if (file.size > 5_000_000) {
      dispatch({ type: 'fail', message: 'That file is larger than 5 MB. Masking is a paste-sized job.' });
      return;
    }
    try {
      const text = await file.text();
      load(text, file.name);
    } catch {
      dispatch({ type: 'fail', message: 'That file could not be read. Try pasting the text instead.' });
    }
  };

  const copy = async () => {
    if (!output) return;
    const ok = await copyText(output);
    dispatch({
      type: 'toast',
      message: ok ? 'Masked CSV copied — values left the page only through your clipboard' : 'Copy failed. Use “Show the exact output” to select it.',
    });
  };

  const download = () => {
    if (!output || !state.table) return;
    const base = state.fileName.replace(/\.csv$/i, '') || 'env';
    downloadText(safeFileName(`${base}.masked.csv`), output);
    dispatch({ type: 'toast', message: 'Downloaded the masked CSV' });
  };

  const keys = useMemo(() => {
    if (!state.table || state.keyColumn === null) return [];
    const seen = new Set<string>();
    const list: string[] = [];
    for (const row of state.table.rows) {
      const key = (row[state.keyColumn] ?? '').trim();
      if (key !== '' && !seen.has(key)) {
        seen.add(key);
        list.push(key);
      }
    }
    return list;
  }, [state.table, state.keyColumn]);

  return (
    <div className="flex min-h-screen flex-col">
      <SkipLink />
      <SiteHeader current="mask" />

      <main id="main" tabIndex={-1} className="mx-auto w-full max-w-[1180px] flex-1 px-4 pb-16 sm:px-6">
        <header className="pt-8 pb-6">
          <h1 className="text-[26px] leading-tight font-semibold tracking-tight text-balance">
            Mask a CSV before an AI reads it
          </h1>
          <p className="mt-2 max-w-[64ch] text-[14px] leading-relaxed text-muted-foreground">
            Paste a CSV of variables, choose what to hide, and copy a still-valid CSV with the values
            replaced. Keys and structure stay, so a model can still reason about your configuration.
            Everything runs in this tab — <Link text="the same rules as the rest of the site" href="/privacy" />.
          </p>
        </header>

        {!state.table ? (
          <section
            className="rounded-lg border border-border bg-card p-4"
            onDragOver={(event) => event.preventDefault()}
            onDrop={(event) => {
              event.preventDefault();
              const file = event.dataTransfer.files?.[0];
              if (file) void openFile(file);
            }}
            aria-labelledby="paste-heading"
          >
            <h2 id="paste-heading" className="text-[15px] font-semibold">
              Paste, drop, or open a CSV
            </h2>
            <p className="mt-1 text-[13px] text-muted-foreground">
              The first row is treated as the header. Commas, semicolons, tabs and pipes all work, and
              quoted values may contain them.
            </p>

            <label className="mt-4 block">
              <span className="sr-only">CSV to mask</span>
              <textarea
                aria-label="CSV to mask"
                value={draft}
                onChange={(event) => setDraft(event.target.value)}
                onPaste={(event) => {
                  const text = event.clipboardData.getData('text');
                  if (text.includes(',') || text.includes('\t')) {
                    // A paste is a deliberate act, the same way it is on the
                    // compare page: parse it rather than making the reader
                    // press a button that adds nothing.
                    event.preventDefault();
                    setDraft(text);
                    dispatch({ type: 'load', text });
                  }
                }}
                spellCheck={false}
                placeholder={'key,value\nDATABASE_URL,postgresql://…\nOPENAI_API_KEY,sk-…'}
                className="mono h-44 w-full resize-y rounded-md border border-border bg-background p-3 text-[12.5px] leading-relaxed outline-none focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/35"
              />
            </label>

            <div className="mt-3 flex flex-wrap items-center gap-2">
              <Button onClick={() => dispatch({ type: 'load', text: draft })} disabled={draft.trim() === ''}>
                <Wand2 aria-hidden="true" />
                Mask values
              </Button>
              <Button variant="outline" onClick={() => fileInput.current?.click()}>
                <FileUp aria-hidden="true" />
                Choose a CSV file
              </Button>
              <input
                ref={fileInput}
                type="file"
                accept=".csv,text/csv,text/plain"
                className="sr-only"
                aria-label="Choose a CSV file"
                onChange={(event) => {
                  const file = event.target.files?.[0];
                  if (file) void openFile(file);
                  event.target.value = '';
                }}
              />
              <Button
                variant="ghost"
                onClick={() => load(SAMPLE_CSV, 'sample.csv')}
              >
                Use an example
              </Button>
            </div>

            {state.error ? (
              <p role="alert" className="mt-3 rounded-md border border-missing/40 bg-missing-tint/40 px-3 py-2 text-[13px] text-missing">
                {state.error}
              </p>
            ) : null}

            <p className="mt-4 text-[12px] text-faint">
              Nothing is uploaded, and nothing is saved: closing the tab discards the file.
            </p>
          </section>
        ) : (
          <div className="grid gap-4">
            <section
              aria-label="What will be shared"
              className="flex flex-wrap items-center gap-x-4 gap-y-2 rounded-lg border border-border bg-card px-4 py-3"
            >
              <ShieldCheck className="size-4 text-ok" aria-hidden="true" />
              <p className="text-[13px]">
                <strong className="font-semibold text-foreground">{masked?.counts.masked ?? 0}</strong>{' '}
                of {(masked?.counts.masked ?? 0) + (masked?.counts.unmasked ?? 0)} values masked
                {masked && masked.counts.empty > 0 ? (
                  <span className="text-muted-foreground"> · {masked.counts.empty} empty</span>
                ) : null}
              </p>
              <span className="text-[12px] text-faint">
                {state.table.rows.length} rows × {state.table.header.length} columns ·{' '}
                {delimiterName(state.table.delimiter)}
              </span>
              <span className="flex-1" />
              <Button variant="ghost" size="sm" onClick={() => dispatch({ type: 'clear' })}>
                <Trash2 aria-hidden="true" />
                Start over
              </Button>
            </section>

            <section aria-labelledby="columns-heading" className="rounded-lg border border-border bg-card p-4">
              <div className="flex flex-wrap items-baseline gap-x-3 gap-y-1">
                <h2 id="columns-heading" className="text-[15px] font-semibold">
                  Columns
                </h2>
                <p className="text-[12.5px] text-muted-foreground">
                  Pick a mode per column. The key column is left readable on purpose — a model needs
                  the names to be useful.
                </p>
                <span className="flex-1" />
                <label className="flex items-center gap-2 text-[12.5px] text-muted-foreground">
                  Characters kept
                  <select
                    aria-label="Characters to keep"
                    value={state.keep}
                    onChange={(event) => dispatch({ type: 'keep', keep: Number(event.target.value) })}
                    className="rounded-sm border border-border bg-background px-2 py-1 text-[12.5px] text-foreground"
                  >
                    {KEEP_OPTIONS.map((value) => (
                      <option key={value} value={value}>
                        {value}
                      </option>
                    ))}
                  </select>
                </label>
                <Button variant="ghost" size="sm" onClick={() => dispatch({ type: 'reset' })}>
                  Reset masks
                </Button>
              </div>

              <div className="mt-3 grid gap-2 sm:grid-cols-2 xl:grid-cols-3">
                {state.table.header.map((_, column) => {
                  const mode = state.columnModes[column] ?? 'none';
                  const name = columnName(column);
                  return (
                    <div
                      key={column}
                      className={cn(
                        'flex items-center gap-2 rounded-md border px-2.5 py-2',
                        mode === 'none' ? 'border-border bg-secondary/40' : 'border-ok/40 bg-ok-tint/30',
                      )}
                    >
                      <span className="mono min-w-0 flex-1 truncate text-[12.5px]" title={name}>
                        {name}
                        {column === state.keyColumn ? (
                          <span className="ml-1.5 rounded-sm bg-secondary px-1 text-[10px] tracking-wide text-muted-foreground uppercase">
                            key
                          </span>
                        ) : null}
                      </span>
                      <select
                        aria-label={`Masking for ${name}`}
                        value={mode}
                        title={MODE_OPTIONS.find((option) => option.value === mode)?.hint}
                        onChange={(event) =>
                          dispatch({ type: 'column', column, mode: event.target.value as MaskMode })
                        }
                        className="max-w-[11rem] rounded-sm border border-border bg-background px-1.5 py-1 text-[12px] text-foreground"
                      >
                        {MODE_OPTIONS.map((option) => (
                          <option key={option.value} value={option.value}>
                            {option.label}
                          </option>
                        ))}
                      </select>
                    </div>
                  );
                })}
              </div>

              {keys.length > 0 ? (
                <details className="mt-3 rounded-md border border-border bg-secondary/30 px-3 py-2">
                  <summary className="cursor-pointer text-[13px] font-medium">
                    Override individual keys ({keys.length})
                  </summary>
                  <p className="mt-1 text-[12px] text-muted-foreground">
                    A key override wins over its column — for the one variable that must stay hidden
                    while the rest of its column is shared.
                  </p>
                  <ul className="mt-2 grid max-h-56 gap-1 overflow-auto sm:grid-cols-2">
                    {keys.map((key) => (
                      <li key={key} className="flex items-center gap-2">
                        <span className="mono min-w-0 flex-1 truncate text-[12px]" title={key}>
                          {key}
                        </span>
                        <select
                          aria-label={`Masking for key ${key}`}
                          value={state.keyModes[key] ?? 'column'}
                          onChange={(event) =>
                            dispatch({
                              type: 'key',
                              key,
                              mode: event.target.value as MaskMode | 'column',
                            })
                          }
                          className="rounded-sm border border-border bg-background px-1.5 py-1 text-[12px] text-foreground"
                        >
                          <option value="column">Use column setting</option>
                          {MODE_OPTIONS.map((option) => (
                            <option key={option.value} value={option.value}>
                              {option.label}
                            </option>
                          ))}
                        </select>
                      </li>
                    ))}
                  </ul>
                </details>
              ) : null}
            </section>

            {masked && masked.warnings.length > 0 ? (
              <section aria-label="Before you share" className="rounded-lg border border-empty/40 bg-empty-tint/25 p-4">
                <h2 className="text-[14px] font-semibold text-empty">Before you share</h2>
                <ul className="mt-2 grid gap-1.5 text-[13px]">
                  {masked.warnings.map((warning) => (
                    <li key={`${warning.kind}-${warning.column}`}>
                      {warning.kind === 'unmasked-secret' ? (
                        <>
                          <span className="mono">{warning.columnName}</span> is not masked
                          {warning.rows.length > 0
                            ? `, and ${warning.rows.length} of its values look like credentials.`
                            : ', and its name suggests it holds a secret.'}
                        </>
                      ) : (
                        <>
                          The key column <span className="mono">{warning.columnName}</span> is masked.
                          Without the key names, the output is much harder to act on.
                        </>
                      )}
                    </li>
                  ))}
                </ul>
              </section>
            ) : null}

            <section aria-labelledby="preview-heading" className="rounded-lg border border-border bg-card">
              <div className="flex flex-wrap items-center gap-2 border-b border-border px-4 py-3">
                <h2 id="preview-heading" className="text-[15px] font-semibold">
                  Preview
                </h2>
                <p className="text-[12.5px] text-muted-foreground">
                  This is exactly what gets copied or downloaded.
                </p>
                <span className="flex-1" />
                <Button size="sm" onClick={() => void copy()}>
                  <Download aria-hidden="true" />
                  Copy masked CSV
                </Button>
                <Button variant="outline" size="sm" onClick={download}>
                  <Download aria-hidden="true" />
                  Download .masked.csv
                </Button>
              </div>

              <div className="overflow-auto">
                <table className="w-full border-collapse text-left text-[12.5px]">
                  <caption className="sr-only">
                    Masked preview: {state.table.rows.length} rows and {state.table.header.length}{' '}
                    columns. Masked values are shown after replacement.
                  </caption>
                  <thead>
                    <tr className="border-b border-border">
                      <th scope="col" className="w-10 px-3 py-2 text-[11px] font-medium text-faint">
                        #
                      </th>
                      {state.table.header.map((_, column) => (
                        <th
                          key={column}
                          scope="col"
                          className="mono px-3 py-2 text-[11.5px] font-medium text-muted-foreground"
                        >
                          {columnName(column)}
                        </th>
                      ))}
                    </tr>
                  </thead>
                  <tbody>
                    {masked?.cells.slice(0, PREVIEW_LIMIT).map((row, rowIndex) => (
                      <tr key={rowIndex} className="border-b border-border/60 last:border-0">
                        <td className="px-3 py-1.5 text-[11px] text-faint tabular-nums">{rowIndex + 1}</td>
                        {row.map((cell, column) => {
                          const id = `${rowIndex}:${column}`;
                          const revealed = state.revealed.includes(id);
                          const shown = revealed ? cell.original : cell.masked;
                          return (
                            <td key={column} className="px-3 py-1.5 align-top">
                              <span className="flex items-start gap-1.5">
                                <span
                                  className={cn(
                                    'mono min-w-0 break-all',
                                    cell.mode !== 'none' && !revealed ? 'text-muted-foreground' : 'text-foreground',
                                  )}
                                >
                                  {shown === '' ? <span className="text-faint">—</span> : shown}
                                </span>
                                {cell.duplicateOf !== null && !revealed ? (
                                  <span
                                    title={`Same value as row ${cell.duplicateOf + 1}`}
                                    className="mt-px shrink-0 rounded-sm bg-secondary px-1 text-[10px] whitespace-nowrap text-muted-foreground"
                                  >
                                    = row {cell.duplicateOf + 1}
                                  </span>
                                ) : null}
                                {cell.mode !== 'none' ? (
                                  <button
                                    type="button"
                                    aria-pressed={revealed}
                                    aria-label={`${revealed ? 'Hide' : 'Show'} the original value in row ${rowIndex + 1}, ${columnName(column)}`}
                                    title={revealed ? 'Show the mask again' : 'Look at the original (this tab only)'}
                                    onClick={() => dispatch({ type: 'reveal', row: rowIndex, column })}
                                    className="mt-px shrink-0 rounded-sm px-1 text-faint hover:text-foreground focus-visible:ring-[3px] focus-visible:ring-ring/35 focus-visible:outline-none"
                                  >
                                    {revealed ? (
                                      <EyeOff className="size-3.5" aria-hidden="true" />
                                    ) : (
                                      <Eye className="size-3.5" aria-hidden="true" />
                                    )}
                                  </button>
                                ) : null}
                              </span>
                            </td>
                          );
                        })}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>

              {state.table.rows.length > PREVIEW_LIMIT ? (
                <p className="border-t border-border px-4 py-2 text-[12px] text-faint">
                  Showing the first {PREVIEW_LIMIT} of {state.table.rows.length} rows. The copy and
                  the download contain every row.
                </p>
              ) : null}

              <div className="border-t border-border px-4 py-3">
                <details>
                  <summary className="cursor-pointer text-[13px] font-medium">Show the exact output</summary>
                  <pre className="mono mt-2 max-h-64 overflow-auto rounded-md border border-border bg-background p-3 text-[12px] whitespace-pre">
                    {output}
                  </pre>
                </details>
              </div>
            </section>

            <section className="rounded-lg border border-border bg-secondary/30 p-4 text-[12.5px] leading-relaxed text-muted-foreground">
              <h2 className="text-[14px] font-semibold text-foreground">What masking does and does not do</h2>
              <ul className="mt-2 grid list-disc gap-1 pl-5">
                <li>
                  It is formatting, not encryption. The asterisks cannot be reversed, but they also
                  prove nothing — treat a masked file as safe to share, not as a secret.
                </li>
                <li>
                  The same value always masks the same way, so duplicate secrets are still visible as
                  duplicates.
                </li>
                <li>
                  Whatever a mode keeps is shared: <span className="mono">sk-live-…</span> is a prefix,
                  not a mask.
                </li>
                <li>The originals never leave this page and are gone when you close or reload the tab.</li>
              </ul>
            </section>
          </div>
        )}
      </main>

      <p aria-live="polite" className="sr-only">
        {state.toast ?? ''}
      </p>
      {state.toast ? (
        <div className="pointer-events-none fixed inset-x-0 bottom-4 z-30 flex justify-center px-4">
          <p className="pointer-events-auto rounded-md border border-border bg-card px-4 py-2 text-[13px] shadow-lg">
            {state.toast}
          </p>
        </div>
      ) : null}
    </div>
  );
}

function Link({ href, text }: { href: string; text: string }) {
  return (
    <a href={href} className="text-foreground underline underline-offset-2">
      {text}
    </a>
  );
}

function delimiterName(delimiter: string): string {
  if (delimiter === '\t') return 'tab-separated';
  if (delimiter === ',') return 'comma-separated';
  if (delimiter === ';') return 'semicolon-separated';
  if (delimiter === '|') return 'pipe-separated';
  return `${delimiter}-separated`;
}
