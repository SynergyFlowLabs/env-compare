import { useMemo, useReducer, useRef, useState } from 'react';
import { Download, Eye, EyeOff, FileUp, ShieldCheck, Trash2, Wand2 } from 'lucide-react';
import {
  maskEnv,
  serializeEnv,
  type MaskMode,
  type MaskWarning,
} from '../../core/mask';
import { initialMaskState, maskReducer } from '../../state/maskReducer';
import { SAMPLE_ENV } from '../../state/sample';
import { SiteHeader } from '../components/SiteHeader';
import { SkipLink } from '../components/SkipLink';
import { Button } from '../components/ui/button';
import { copyText, downloadText, safeFileName } from '../lib/clipboard';
import { cn } from '../lib/utils';

/**
 * Mask an env file before an AI reads it (issue #10, corrected by issue #13).
 *
 * The compare tool answers "what is missing from my .env". This answers the
 * neighbouring question: how do I let a model read the shape of a configuration
 * without the secrets in it? Same promise, second surface.
 *
 * The shape is fixed on purpose. A `.env` file has keys and values; it does not
 * have columns, delimiters or headers, and pretending otherwise is how the
 * first version ended up printing a real value as a column title. So: exactly
 * two columns, comments and blank lines counted but never listed, and the first
 * line is a variable like any other.
 *
 * Three rules shaped the interface:
 *   1. The preview *is* the output. There is no separate "masked" file to trust;
 *      the table is generated by the same function that writes the text.
 *   2. Nothing is destructive. The original stays in memory, every mask can be
 *      undone, and the export is always derived from it.
 *   3. Masking is described as formatting, not encryption, because claiming
 *      more than that would be a lie a reader might rely on.
 */

const MODE_OPTIONS: Array<{ value: MaskMode; label: string; hint: string }> = [
  { value: 'none', label: 'Don’t mask', hint: 'Value is shared exactly as written' },
  { value: 'hide', label: 'Hide completely', hint: 'Replaced by 8 stars; even the length is hidden' },
  { value: 'start', label: 'Mask the start', hint: 'The last characters stay visible' },
  { value: 'middle', label: 'Mask the middle', hint: 'The first and last characters stay visible' },
  { value: 'end', label: 'Mask the end', hint: 'The first characters stay visible' },
];

const KEEP_OPTIONS = [2, 4, 6, 8];

export function Mask() {
  const [state, dispatch] = useReducer(maskReducer, initialMaskState);
  const [draft, setDraft] = useState('');
  const fileInput = useRef<HTMLInputElement>(null);

  const masked = useMemo(
    () =>
      state.source
        ? maskEnv(state.source, {
            valueMode: state.valueMode,
            keyModes: state.keyModes,
            keep: state.keep,
          })
        : null,
    [state.source, state.valueMode, state.keyModes, state.keep],
  );

  const output = useMemo(
    () =>
      masked && state.source
        ? serializeEnv(
            masked.entries.map((entry) => ({ key: entry.key, value: entry.masked })),
            { lineEnding: state.source.lineEnding },
          )
        : '',
    [masked, state.source],
  );

  const load = (text: string, fileName = '') => {
    dispatch({ type: 'load', text, fileName });
    setDraft(text);
  };

  const openFile = async (file: File) => {
    if (file.size > 5_000_000) {
      dispatch({ type: 'fail', message: 'That file is larger than 5 MB. Masking is a paste-sized job.' });
      return;
    }
    try {
      load(await file.text(), file.name);
    } catch {
      dispatch({ type: 'fail', message: 'That file could not be read. Try pasting the text instead.' });
    }
  };

  const copy = async () => {
    if (!output) return;
    const ok = await copyText(output);
    dispatch({
      type: 'toast',
      message: ok ? 'Masked env copied — the values left only through your clipboard' : 'Copy failed. Use “Show the exact output” to select it.',
    });
  };

  const download = () => {
    if (!output || !state.source) return;
    const base = state.fileName.replace(/^\.env\.?/i, '').replace(/\.env$/i, '') || 'env';
    downloadText(safeFileName(base === '' ? 'env.masked.env' : `${base}.masked.env`), output);
    dispatch({ type: 'toast', message: 'Downloaded the masked env file' });
  };

  return (
    <div className="flex min-h-screen flex-col">
      <SkipLink />
      <SiteHeader current="mask" />

      <main id="main" tabIndex={-1} className="mx-auto w-full max-w-[1180px] flex-1 px-4 pb-16 sm:px-6">
        <header className="pt-8 pb-6">
          <h1 className="text-[26px] leading-tight font-semibold tracking-tight text-balance">
            Mask an env file before an AI reads it
          </h1>
          <p className="mt-2 max-w-[64ch] text-[14px] leading-relaxed text-muted-foreground">
            Paste a <code>.env</code>, choose what to hide, and copy a valid env file with the values
            replaced. Keys and structure stay, so a model can still reason about your configuration.
            Everything runs in this tab —{' '}
            <a href="/privacy" className="text-foreground underline underline-offset-2">
              the same rules as the rest of the site
            </a>
            .
          </p>
        </header>

        {!state.source ? (
          <section
            className="rounded-lg border border-border bg-card p-4"
            onDragOver={(event) => event.preventDefault()}
            onDrop={(event) => {
              event.preventDefault();
              const file = event.dataTransfer.files?.[0];
              if (file) void openFile(file);
            }}
            aria-labelledby="paste-heading"
          >
            <h2 id="paste-heading" className="text-[15px] font-semibold">
              Paste, drop, or open a .env file
            </h2>
            <p className="mt-1 text-[13px] text-muted-foreground">
              One <code>KEY=value</code> per line. Comments and blank lines are skipped, and reported,
              but never treated as variables.
            </p>

            <label className="mt-4 block">
              <span className="sr-only">Env text to mask</span>
              <textarea
                aria-label="Env text to mask"
                value={draft}
                onChange={(event) => setDraft(event.target.value)}
                onPaste={(event) => {
                  const text = event.clipboardData.getData('text');
                  if (text.includes('=')) {
                    // A paste is a deliberate act, the same way it is on the
                    // compare page: read it rather than making the reader press
                    // a button that adds nothing.
                    event.preventDefault();
                    load(text);
                  }
                }}
                spellCheck={false}
                placeholder={'# optional comments\nDATABASE_URL=postgresql://…\nOPENAI_API_KEY=sk-…'}
                className="mono h-44 w-full resize-y rounded-md border border-border bg-background p-3 text-[12.5px] leading-relaxed outline-none focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/35"
              />
            </label>

            <div className="mt-3 flex flex-wrap items-center gap-2">
              <Button onClick={() => dispatch({ type: 'load', text: draft })} disabled={draft.trim() === ''}>
                <Wand2 aria-hidden="true" />
                Mask values
              </Button>
              <Button variant="outline" onClick={() => fileInput.current?.click()}>
                <FileUp aria-hidden="true" />
                Choose a .env file
              </Button>
              <input
                ref={fileInput}
                type="file"
                className="sr-only"
                aria-label="Choose a .env file"
                onChange={(event) => {
                  const file = event.target.files?.[0];
                  if (file) void openFile(file);
                  event.target.value = '';
                }}
              />
              <Button variant="ghost" onClick={() => load(SAMPLE_ENV, '.env')}>
                Use an example
              </Button>
            </div>

            {state.error ? (
              <p role="alert" className="mt-3 rounded-md border border-missing/40 bg-missing-tint/40 px-3 py-2 text-[13px] text-missing">
                {state.error}
              </p>
            ) : null}

            <p className="mt-4 text-[12px] text-faint">
              Nothing is uploaded, and nothing is saved: closing the tab discards the file.
            </p>
          </section>
        ) : (
          <div className="grid gap-4">
            <section
              aria-label="What will be shared"
              className="flex flex-wrap items-center gap-x-4 gap-y-2 rounded-lg border border-border bg-card px-4 py-3"
            >
              <ShieldCheck className="size-4 text-ok" aria-hidden="true" />
              <p className="text-[13px]">
                <strong className="font-semibold text-foreground">{masked?.counts.masked ?? 0}</strong>{' '}
                of {(masked?.counts.masked ?? 0) + (masked?.counts.unmasked ?? 0)} values masked
                {masked && masked.counts.empty > 0 ? (
                  <span className="text-muted-foreground"> · {masked.counts.empty} empty</span>
                ) : null}
              </p>
              <span className="text-[12px] text-faint">
                {state.source.entries.length} variables · {skippedNote(state.source.skipped)}
              </span>
              <span className="flex-1" />
              <Button variant="ghost" size="sm" onClick={() => dispatch({ type: 'clear' })}>
                <Trash2 aria-hidden="true" />
                Start over
              </Button>
            </section>

            {state.source.diagnostics.some((item) => item.code === 'DUP_KEY') ? (
              <p className="rounded-md border border-empty/40 bg-empty-tint/25 px-3 py-2 text-[12.5px] text-empty">
                {duplicateNote(state.source.entries)} Last one wins, the way <code>dotenv</code> reads it.
              </p>
            ) : null}

            <section aria-labelledby="values-heading" className="rounded-lg border border-border bg-card p-4">
              <div className="flex flex-wrap items-baseline gap-x-3 gap-y-2">
                <h2 id="values-heading" className="text-[15px] font-semibold">
                  Values
                </h2>
                <p className="text-[12.5px] text-muted-foreground">
                  One setting for every value, then per-key overrides. Keys are never masked.
                </p>
                <span className="flex-1" />
                <label className="flex items-center gap-2 text-[12.5px] text-muted-foreground">
                  Characters kept
                  <select
                    aria-label="Characters to keep"
                    value={state.keep}
                    onChange={(event) => dispatch({ type: 'keep', keep: Number(event.target.value) })}
                    className="rounded-sm border border-border bg-background px-2 py-1 text-[12.5px] text-foreground"
                  >
                    {KEEP_OPTIONS.map((value) => (
                      <option key={value} value={value}>
                        {value}
                      </option>
                    ))}
                  </select>
                </label>
                <Button variant="ghost" size="sm" onClick={() => dispatch({ type: 'reset' })}>
                  Reset masks
                </Button>
              </div>

              <div className="mt-3 flex flex-wrap items-center gap-2">
                <label className="flex items-center gap-2 text-[13px]">
                  <span className="text-muted-foreground">All values</span>
                  <select
                    aria-label="Masking for all values"
                    value={state.valueMode}
                    onChange={(event) => dispatch({ type: 'mode', mode: event.target.value as MaskMode })}
                    className="rounded-sm border border-border bg-background px-2 py-1 text-[13px] text-foreground"
                  >
                    {MODE_OPTIONS.map((option) => (
                      <option key={option.value} value={option.value} title={option.hint}>
                        {option.label}
                      </option>
                    ))}
                  </select>
                </label>
                <span className="text-[12px] text-faint">
                  {Object.keys(state.keyModes).length} key override
                  {Object.keys(state.keyModes).length === 1 ? '' : 's'}
                </span>
              </div>

              <details className="mt-3 rounded-md border border-border bg-secondary/30 px-3 py-2" open={Object.keys(state.keyModes).length > 0}>
                <summary className="cursor-pointer text-[13px] font-medium">
                  Per-key overrides ({state.source.entries.length})
                </summary>
                <p className="mt-1 text-[12px] text-muted-foreground">
                  A key override wins over the setting above — for the one variable that must stay
                  hidden while the rest of the file is shared, or the reverse.
                </p>
                <ul className="mono mt-2 grid max-h-64 gap-1 overflow-auto sm:grid-cols-2">
                  {state.source.entries.map((entry) => (
                    <li key={`${entry.line}-${entry.key}`} className="flex items-center gap-2">
                      <span className="min-w-0 flex-1 truncate text-[12px]" title={entry.key}>
                        {entry.key}
                      </span>
                      <select
                        aria-label={`Masking for ${entry.key}`}
                        value={state.keyModes[entry.key] ?? 'file'}
                        onChange={(event) =>
                          dispatch({
                            type: 'key',
                            key: entry.key,
                            mode: event.target.value as MaskMode | 'file',
                          })
                        }
                        className="max-w-[10rem] rounded-sm border border-border bg-background px-1.5 py-1 text-[12px] text-foreground"
                      >
                        <option value="file">Use the value setting</option>
                        {MODE_OPTIONS.map((option) => (
                          <option key={option.value} value={option.value}>
                            {option.label}
                          </option>
                        ))}
                      </select>
                    </li>
                  ))}
                </ul>
              </details>
            </section>

            {masked && masked.warnings.length > 0 ? (
              <section aria-label="Before you share" className="rounded-lg border border-empty/40 bg-empty-tint/25 p-4">
                <h2 className="text-[14px] font-semibold text-empty">Before you share</h2>
                <ul className="mt-2 grid gap-1.5 text-[13px]">
                  {masked.warnings.map((warning) => (
                    <li key={warning.kind}>
                      {describeWarning(warning)}
                    </li>
                  ))}
                </ul>
              </section>
            ) : null}

            <section aria-labelledby="preview-heading" className="rounded-lg border border-border bg-card">
              <div className="flex flex-wrap items-center gap-2 border-b border-border px-4 py-3">
                <h2 id="preview-heading" className="text-[15px] font-semibold">
                  Preview
                </h2>
                <p className="text-[12.5px] text-muted-foreground">
                  This is exactly what gets copied or downloaded.
                </p>
                <span className="flex-1" />
                <Button size="sm" onClick={() => void copy()}>
                  <Download aria-hidden="true" />
                  Copy masked env
                </Button>
                <Button variant="outline" size="sm" onClick={download}>
                  <Download aria-hidden="true" />
                  Download .masked.env
                </Button>
              </div>

              <div className="overflow-auto">
                <table className="w-full border-collapse text-left text-[12.5px]">
                  <caption className="sr-only">
                    Masked preview: {state.source.entries.length} variables and their values after
                    masking. Comments and blank lines are not shown.
                  </caption>
                  <thead>
                    <tr className="border-b border-border">
                      <th scope="col" className="w-10 px-3 py-2 text-[11px] font-medium text-faint">
                        #
                      </th>
                      <th scope="col" className="w-[38%] px-3 py-2 text-[11.5px] font-medium text-muted-foreground">
                        key
                      </th>
                      <th scope="col" className="px-3 py-2 text-[11.5px] font-medium text-muted-foreground">
                        value
                      </th>
                    </tr>
                  </thead>
                  <tbody>
                    {masked?.entries.map((entry, index) => {
                      const revealed = state.revealed.includes(index);
                      const shown = revealed ? entry.original : entry.masked;
                      return (
                        <tr key={`${index}-${entry.key}`} className="border-b border-border/60 last:border-0">
                          <td className="px-3 py-1.5 align-top text-[11px] text-faint tabular-nums">
                            {index + 1}
                          </td>
                          <td className="mono px-3 py-1.5 align-top break-all text-foreground">
                            {entry.key}
                            {entry.duplicateOf !== null && !revealed ? (
                              <span
                                title={`Same value as ${masked.entries[entry.duplicateOf]?.key ?? 'an earlier key'}`}
                                className="ml-1.5 rounded-sm bg-secondary px-1 text-[10px] whitespace-nowrap text-muted-foreground"
                              >
                                = {masked.entries[entry.duplicateOf]?.key ?? 'earlier'}
                              </span>
                            ) : null}
                          </td>
                          <td className="px-3 py-1.5 align-top">
                            <span className="flex items-start gap-1.5">
                              <span
                                className={cn(
                                  'mono min-w-0 break-all',
                                  entry.mode !== 'none' && !revealed ? 'text-muted-foreground' : 'text-foreground',
                                )}
                              >
                                {shown === '' ? <span className="text-faint">—</span> : shown}
                              </span>
                              {entry.mode !== 'none' ? (
                                <button
                                  type="button"
                                  aria-pressed={revealed}
                                  aria-label={`${revealed ? 'Hide' : 'Show'} the original value of ${entry.key}`}
                                  title={revealed ? 'Show the mask again' : 'Look at the original (this tab only)'}
                                  onClick={() => dispatch({ type: 'reveal', index })}
                                  className="mt-px shrink-0 rounded-sm px-1 text-faint hover:text-foreground focus-visible:ring-[3px] focus-visible:ring-ring/35 focus-visible:outline-none"
                                >
                                  {revealed ? (
                                    <EyeOff className="size-3.5" aria-hidden="true" />
                                  ) : (
                                    <Eye className="size-3.5" aria-hidden="true" />
                                  )}
                                </button>
                              ) : null}
                            </span>
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>

              <div className="border-t border-border px-4 py-3">
                <details>
                  <summary className="cursor-pointer text-[13px] font-medium">Show the exact output</summary>
                  <pre className="mono mt-2 max-h-64 overflow-auto rounded-md border border-border bg-background p-3 text-[12px] whitespace-pre">
                    {output}
                  </pre>
                </details>
              </div>
            </section>

            <section className="rounded-lg border border-border bg-secondary/30 p-4 text-[12.5px] leading-relaxed text-muted-foreground">
              <h2 className="text-[14px] font-semibold text-foreground">What masking does and does not do</h2>
              <ul className="mt-2 grid list-disc gap-1 pl-5">
                <li>
                  It is formatting, not encryption. The asterisks cannot be reversed, but they also
                  prove nothing — treat a masked file as safe to share, not as a secret.
                </li>
                <li>
                  The same value always masks the same way, so a secret reused under two keys is still
                  visible as a duplicate.
                </li>
                <li>
                  Whatever a mode keeps is shared: <span className="mono">sk-live-…</span> is a prefix,
                  not a mask.
                </li>
                <li>Comments and blank lines are not shared, and the originals are gone when you close or reload the tab.</li>
              </ul>
            </section>
          </div>
        )}
      </main>

      <p aria-live="polite" className="sr-only">
        {state.toast ?? ''}
      </p>
      {state.toast ? (
        <div className="pointer-events-none fixed inset-x-0 bottom-4 z-30 flex justify-center px-4">
          <p className="pointer-events-auto rounded-md border border-border bg-card px-4 py-2 text-[13px] shadow-lg">
            {state.toast}
          </p>
        </div>
      ) : null}
    </div>
  );
}

/** "4 comment lines and 1 blank line skipped", in the file's own terms. */
function skippedNote(skipped: { comments: number; blank: number; unreadable: number }): string {
  const parts: string[] = [];
  if (skipped.comments > 0) parts.push(`${skipped.comments} comment line${skipped.comments === 1 ? '' : 's'}`);
  if (skipped.blank > 0) parts.push(`${skipped.blank} blank line${skipped.blank === 1 ? '' : 's'}`);
  if (skipped.unreadable > 0) parts.push(`${skipped.unreadable} unreadable line${skipped.unreadable === 1 ? '' : 's'}`);
  if (parts.length === 0) return 'no comments';
  return `${parts.join(', ')} skipped`;
}

function duplicateNote(entries: Array<{ key: string; duplicates: number }>): string {
  const repeated = entries.filter((entry) => entry.duplicates > 0);
  if (repeated.length === 0) return '';
  const names = repeated.map((entry) => entry.key).join(', ');
  return `${names} ${repeated.length === 1 ? 'is' : 'are'} defined more than once.`;
}

function describeWarning(warning: MaskWarning): string {
  const list = warning.keys.join(', ');
  if (warning.kind === 'unmasked-secret') {
    return `${list} ${warning.keys.length === 1 ? 'is' : 'are'} still visible and ${
      warning.keys.length === 1 ? 'looks' : 'look'
    } like a credential.`;
  }
  return `${list} ${warning.keys.length === 1 ? 'has' : 'have'} a name that suggests a secret and ${
    warning.keys.length === 1 ? 'is' : 'are'
  } still visible.`;
}
